// contracts emits the supported Go DTOs as TypeScript. Unsupported types fail.
package main

import (
	"encoding/json"
	"fmt"
	"go-quick/internal/workspace"
	"os"
	"reflect"
	"sort"
	"strings"
)

func main() {
	providers := workspace.Providers(nil)
	names := make([]string, 0, len(providers))
	for name := range providers {
		names = append(names, name)
	}
	sort.Strings(names)
	var output strings.Builder
	output.WriteString("// Generated by go run ./cmd/contracts. Do not edit.\nexport interface Sources {\n")
	params := map[string][]string{}
	for _, name := range names {
		provider := providers[name]
		fmt.Fprintf(&output, "  %q: %s\n", name, ts(reflect.TypeOf(provider.Output)))
		params[name] = provider.Params
	}
	output.WriteString("}\n")
	if err := json.NewEncoder(os.Stdout).Encode(struct {
		TypeScript string              `json:"typescript"`
		Sources    map[string][]string `json:"sources"`
	}{output.String(), params}); err != nil {
		panic(err)
	}
}

func ts(t reflect.Type) string {
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int:
		return "number"
	case reflect.Slice:
		return "Array<" + ts(t.Elem()) + ">"
	case reflect.Struct:
		fields := []string{}
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			name := strings.Split(f.Tag.Get("json"), ",")[0]
			if name == "" || name == "-" {
				panic("DTO fields require explicit JSON names")
			}
			fields = append(fields, fmt.Sprintf("%q: %s", name, ts(f.Type)))
		}
		return "{ " + strings.Join(fields, "; ") + " }"
	default:
		panic("unsupported DTO type: " + t.String())
	}
}
