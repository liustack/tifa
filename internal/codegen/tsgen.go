// rootID is the TanStack ID of the root route.
const rootID = "__root__"

// reservedNames are the exports of a +route module. Declarations of recursive types avoid them.
var reservedNames = []string{"Data", "Params", "route", "getRouteApi"}

// tsNode is one route of the TanStack route tree: a page, or a Layout with pages in scope.
type tsNode struct {
	id       string // manifest ID, empty for the framework's own root
	file     string // "route" or "layout", the base name of the TSX file
	tsx      bool
	exports  []string
	load     *analyze.Load
	segs     []string // ServeMux segments of the route's full path
	parent   *tsNode
	children []*tsNode
	path     string // the path option, relative to the parent, empty for the root and pathless Layouts
	custom   string // the id option of a pathless Layout
	routeID  string // the TanStack route ID
	variable string
}

func (n *tsNode) exported(name string) bool { return slices.Contains(n.exports, name) }

// generateTS writes the route tree, a +route module for every route of the tree, the two entries,
// the tsconfig and the runtime.
// An application without pages has no TypeScript and gets none.
func generateTS(root string, m *analyze.Manifest, dev bool) (map[string][]byte, error) {
	if !slices.ContainsFunc(m.Routes, func(r analyze.Route) bool { return r.Page }) {
		return nil, nil
	}
	tree, nodes, err := buildTree(root, m)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{"routes.tsx": routesModule(tree, nodes)}
	for _, n := range nodes {
		if n.id == "" {
			continue
		}
		module, err := routeModule(n)
		if err != nil {
			return nil, err
		}
		files[n.id+"/+route.ts"] = module
	}
	files["server.ts"] = []byte(tsHeader + `import "./runtime/host"
import { serve } from "./runtime/server"
import { routeTree } from "./routes"

serve(routeTree)
`)
	client := tsHeader + `import { hydrate } from "./runtime/browser"
import { routeTree } from "./routes"
`
	if dev {
		client += `import "./runtime/dev-client.js"` + "\n"
		files["runtime/dev-client.js"] = []byte(js.DevClient)
	}
	files["client.ts"] = []byte(client + "\nhydrate(routeTree)\n")
	files["tsconfig.json"] = []byte(tsconfig)
	err = fs.WalkDir(js.Runtime, "runtime", func(name string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		data, err := fs.ReadFile(js.Runtime, name)
		files[name] = data
		return err
	})
	if err != nil {
		return nil, err
	}
	return files, nil
}

const tsHeader = "// Code generated by tifa. DO NOT EDIT.\n"

// tsconfig names the generated files one by one, because TypeScript's include patterns skip
// directories whose name starts with a dot, such as .tifa. It makes TypeScript see each generated .tifa/app/<dir>/+route.ts as if it were next to
// the TSX of that directory (rootDirs), and resolves the module tifa/client to the runtime
// (paths). Paths in a tsconfig are relative to the file that declares them, so an application's
// tsconfig.json can extend this one.
const tsconfig = `{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "jsx": "react-jsx",
    "strict": true,
    "noEmit": true,
    "esModuleInterop": true,
    "skipLibCheck": true,
    "lib": ["ES2022", "DOM", "DOM.Iterable"],
    "types": [],
    "rootDirs": ["..", "."],
    "paths": {
      "tifa/client": ["./runtime/client.ts"]
    }
  },
  "include": ["../app", "routes.tsx", "server.ts", "client.ts", "runtime/env.d.ts"]
}
`

// buildTree places pages and the Layouts that have pages in scope into the TanStack route tree.
// The app Layout, when it has pages, is the root route. Otherwise the framework's root renders
// the default document. A Layout's path is the common prefix of its pages' Paths minus its
// parent's, and a Layout whose prefix equals its parent's is pathless.
func buildTree(root string, m *analyze.Manifest) (*tsNode, []*tsNode, error) {
	pages := map[string]bool{}
	for _, r := range m.Routes {
		pages[r.ID] = r.Page
	}
	inTree := map[string]bool{}
	for _, l := range m.Layouts {
		inTree[l.ID] = slices.ContainsFunc(l.Routes, func(id string) bool { return pages[id] })
	}

	top := &tsNode{routeID: rootID, variable: "root"}
	nodes := []*tsNode{top}
	byID := map[string]*tsNode{}
	if inTree["app"] {
		top.id = "app"
		byID["app"] = top
	}
	nearest := func(ids []string) *tsNode {
		for _, id := range slices.Backward(ids) {
			if n, ok := byID[id]; ok {
				return n
			}
		}
		return top
	}
	for _, l := range m.Layouts {
		if !inTree[l.ID] {
			continue
		}
		n := byID[l.ID]
		if n == nil {
			var chain []string
			for p := l.Parent; p != ""; p = parentOf(m, p) {
				chain = append([]string{p}, chain...)
			}
			n = &tsNode{id: l.ID, parent: nearest(chain), segs: segments(l.Path)}
			byID[l.ID] = n
			nodes = append(nodes, n)
		}
		n.file, n.tsx, n.load = "layout", l.TSX, l.Load
	}
	if top.id != "" && top.load != nil && len(top.load.Params) > 0 {
		return nil, nil, fmt.Errorf("app/layout.go: the root Layout's Load reads path parameter %q, but the root route has no path", top.load.Params[0])
	}
	for _, r := range m.Routes {
		if r.Page {
			nodes = append(nodes, &tsNode{id: r.ID, file: "route", tsx: true, load: r.Load, parent: nearest(r.Layouts), segs: segments(r.Path)})
		}
	}

	for i, n := range nodes {
		if n.tsx {
			file := filepath.Join(root, filepath.FromSlash(n.id), n.file+".tsx")
			exports, err := exportsOf(file)
			if err != nil {
				return nil, nil, err
			}
			if !slices.Contains(exports, "default") {
				return nil, nil, fmt.Errorf("%s/%s.tsx: export the component as default", n.id, n.file)
			}
			n.exports = exports
		}
		if n.parent == nil {
			continue
		}
		n.variable = fmt.Sprintf("r%d", i)
		n.parent.children = append(n.parent.children, n)
		if len(n.segs) < len(n.parent.segs) || !slices.Equal(n.segs[:len(n.parent.segs)], n.parent.segs) {
			return nil, nil, fmt.Errorf("%s: path /%s does not start with its parent's /%s", n.id, strings.Join(n.segs, "/"), strings.Join(n.parent.segs, "/"))
		}
		rel := make([]string, 0, len(n.segs))
		for _, s := range n.segs[len(n.parent.segs):] {
			rel = append(rel, routerSegment(s))
		}
		custom := strings.Join(rel, "/")
		switch {
		case n.file == "route" && custom == "":
			n.path, custom = "/", "/"
		case n.file == "route":
			n.path = custom
		case custom == "":
			n.custom = "_" + strings.ReplaceAll(strings.TrimPrefix(n.id, "app/"), "/", ".")
			custom = n.custom
		default:
			n.path = custom
		}
		parentID := n.parent.routeID
		if parentID == rootID {
			parentID = ""
		}
		n.routeID = cleanPath(parentID + "/" + custom)
	}
	return top, nodes, nil
}

func parentOf(m *analyze.Manifest, id string) string {
	for _, l := range m.Layouts {
		if l.ID == id {
			return l.Parent
		}
	}
	panic("codegen: unknown Layout " + id)
}

// segments splits a ServeMux path into its segments, none for "/".
func segments(p string) []string {
	if p == "/" {
		return nil
	}
	return strings.Split(strings.TrimPrefix(p, "/"), "/")
}

// routerSegment turns a ServeMux segment into TanStack syntax: {name} is $name and {name...} is $.
func routerSegment(s string) string {
	switch {
	case strings.HasSuffix(s, "...}"):
		return "$"
	case strings.HasPrefix(s, "{"):
		return "$" + s[1:len(s)-1]
	}
	return s
}

// paramKey is the TanStack name of a ServeMux parameter segment, empty for a literal.
func paramKey(s string) string {
	switch {
	case strings.HasSuffix(s, "...}"):
		return "_splat"
	case strings.HasPrefix(s, "{"):
		return s[1 : len(s)-1]
	}
	return ""
}

func params(n *tsNode) []string {
	var keys []string
	for _, s := range n.segs {
		if k := paramKey(s); k != "" {
			keys = append(keys, k)
		}
	}
	return keys
}

// cleanPath is cleanPath of TanStack's router-core: runs of slashes become one.
func cleanPath(p string) string {
	for strings.Contains(p, "//") {
		p = strings.ReplaceAll(p, "//", "/")
	}
	return p
}

func jsString(s string) string {
	b, err := json.Marshal(s)
	if err != nil {
		panic(err) // a string always marshals
	}
	return string(b)
}

func jsStrings(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = jsString(v)
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

// routesModule writes routes.tsx: one route per node, the tree, and the router type registration
// that gives getRouteApi its types.
func routesModule(top *tsNode, nodes []*tsNode) []byte {
	var imports, body strings.Builder
	runtime := map[string]bool{"createAppRouter": true}
	for i, n := range nodes {
		if n.tsx {
			fmt.Fprintf(&imports, "import * as m%d from %s\n", i, jsString(path.Join("..", n.id, n.file)))
		}
		if n.load != nil {
			fmt.Fprintf(&imports, "import type { Data as D%d } from %s\n", i, jsString("./"+n.id+"/+route"))
		}
	}
	for i, n := range nodes {
		var opts []string
		if n.parent == nil {
			fmt.Fprintf(&body, "const root = createRootRouteWithContext<RouterContext>()({\n")
		} else {
			fmt.Fprintf(&body, "const %s = createRoute({\n", n.variable)
			opts = append(opts, "getParentRoute: () => "+n.parent.variable)
			if n.custom != "" {
				opts = append(opts, "id: "+jsString(n.custom))
			} else {
				opts = append(opts, "path: "+jsString(n.path))
			}
		}
		switch {
		case n.tsx:
			opts = append(opts, fmt.Sprintf("component: m%d.default", i))
		case n.parent == nil:
			opts = append(opts, "component: DefaultDocument")
			runtime["DefaultDocument"] = true
		}
		if n.exported("head") {
			opts = append(opts, fmt.Sprintf("head: m%d.head", i))
		}
		switch {
		case n.exported("Error"):
			opts = append(opts, fmt.Sprintf("errorComponent: m%d.Error", i))
		case n.parent == nil:
			opts = append(opts, "errorComponent: DefaultError")
			runtime["DefaultError"] = true
		}
		switch {
		case n.exported("NotFound"):
			opts = append(opts, fmt.Sprintf("notFoundComponent: m%d.NotFound", i))
		case n.parent == nil:
			opts = append(opts, "notFoundComponent: DefaultNotFound")
			runtime["DefaultNotFound"] = true
		}
		var query []string
		if n.load != nil {
			query = n.load.AllQuery
			runtime["load"] = true
			opts = append(opts,
				fmt.Sprintf("loader: ({ context, location }) => load<D%d>(context, %s, location)", i, jsString(n.id)),
				"staleTime: Infinity")
			if len(query) > 0 {
				runtime["pick"] = true
				opts = append(opts, fmt.Sprintf("loaderDeps: ({ search }) => pick(search, %s)", jsStrings(query)))
			}
		}
		var args, deps []string
		if keys := params(n); len(keys) > 0 {
			args = append(args, "params")
			for _, k := range keys {
				deps = append(deps, "params."+k)
			}
		}
		if len(query) > 0 {
			args = append(args, "search")
			deps = append(deps, fmt.Sprintf("pick(search, %s)", jsStrings(query)))
		}
		if len(deps) > 0 {
			opts = append(opts, fmt.Sprintf("remountDeps: ({ %s }) => [%s]", strings.Join(args, ", "), strings.Join(deps, ", ")))
		}
		for _, o := range opts {
			body.WriteString("  " + o + ",\n")
		}
		body.WriteString("})\n\n")
	}
	fmt.Fprintf(&body, "export const routeTree = %s\n", subtree(top))
	body.WriteString(`
declare module "@tanstack/react-router" {
  interface Register {
    router: ReturnType<typeof createAppRouter<typeof routeTree>>
  }
}
`)

	var out strings.Builder
	out.WriteString(tsHeader)
	out.WriteString(`import { createRootRouteWithContext, createRoute } from "@tanstack/react-router"` + "\n")
	var names []string
	for _, name := range []string{"createAppRouter", "DefaultDocument", "DefaultError", "DefaultNotFound", "load", "pick"} {
		if runtime[name] {
			names = append(names, name)
		}
	}
	names = append(names, "type RouterContext")
	fmt.Fprintf(&out, `import { %s } from "./runtime/router"`+"\n", strings.Join(names, ", "))
	out.WriteString(imports.String())
	out.WriteString("\n")
	out.WriteString(body.String())
	return []byte(out.String())
}

func subtree(n *tsNode) string {
	if len(n.children) == 0 {
		return n.variable
	}
	children := make([]string, len(n.children))
	for i, c := range n.children {
		children[i] = subtree(c)
	}
	return n.variable + ".addChildren([" + strings.Join(children, ", ") + "])"
}

// routeModule writes the +route module of a route or Layout: route for its hooks, Data for its
// Load result and Params for its path parameters.
func routeModule(n *tsNode) ([]byte, error) {
	var b strings.Builder
	b.WriteString(tsHeader)
	b.WriteString(`import { getRouteApi } from "@tanstack/react-router"` + "\n\n")
	data := "undefined"
	if n.load != nil {
		if n.load.Result == nil {
			return nil, fmt.Errorf("codegen: %s: the manifest carries no Load result type, analyze the application in this process", n.id)
		}
		ts, decls, err := analyze.TSShape(n.load.Result, reservedNames)
		if err != nil {
			return nil, fmt.Errorf("codegen: %s: %w", n.id, err)
		}
		for _, d := range decls {
			b.WriteString(d + "\n")
		}
		if len(decls) > 0 {
			b.WriteString("\n")
		}
		data = ts
	}
	if n.load != nil {
		fmt.Fprintf(&b, "// Data is what the Go Load of %s returns, as JSON.\n", n.id)
	} else {
		fmt.Fprintf(&b, "// %s has no Go Load.\n", n.id)
	}
	fmt.Fprintf(&b, "export type Data = %s\n\n", data)
	keys := params(n)
	paramsType := "Record<string, never>"
	if len(keys) > 0 {
		props := make([]string, len(keys))
		for i, k := range keys {
			props[i] = k + ": string"
		}
		paramsType = "{ " + strings.Join(props, "; ") + " }"
	}
	fmt.Fprintf(&b, "export type Params = %s\n\n", paramsType)
	fmt.Fprintf(&b, "export const route = getRouteApi(%s)\n", jsString(n.routeID))
	return []byte(b.String()), nil
}
