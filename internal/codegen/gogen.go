package codegen

import (
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"github.com/liustack/tifa/internal/analyze"
)

const header = "// Code generated by tifa. DO NOT EDIT.\n\n"

// generateGo writes main.go, which hands the application to server.Main, and routes.go, which
// lists the Layouts and routes with direct references to their Load and OnXxx functions.
func generateGo(m *analyze.Manifest, configName string) (map[string][]byte, error) {
	imports := goImports{byPath: map[string]string{}}

	var routes strings.Builder
	routes.WriteString("var layouts = []server.Layout{\n")
	for _, l := range m.Layouts {
		fmt.Fprintf(&routes, "{\nID: %q,\n", l.ID)
		if l.Load != nil {
			fmt.Fprintf(&routes, "Load: %s,\n", imports.load(l.Package, l.ID))
		}
		fmt.Fprintf(&routes, "SSR: %t,\n},\n", l.SSR)
	}
	routes.WriteString("}\n\nvar routes = []server.Route{\n")
	for _, r := range m.Routes {
		fmt.Fprintf(&routes, "{\nID: %q,\nPath: %q,\nPage: %t,\n", r.ID, r.Path, r.Page)
		if r.Load != nil {
			fmt.Fprintf(&routes, "Load: %s,\n", imports.load(r.Package, r.ID))
		}
		for _, method := range r.Methods {
			name := "On" + method[:1] + strings.ToLower(method[1:])
			fmt.Fprintf(&routes, "%s: %s.%s,\n", name, imports.alias(r.Package, r.ID), name)
		}
		fmt.Fprintf(&routes, "SSR: %t,\nCache: %t,\nLayouts: %s,\n},\n", r.SSR, r.Cache, stringSlice(r.Layouts))
	}
	routes.WriteString("}\n")

	var src strings.Builder
	src.WriteString(header + "package main\n\nimport (\n")
	if imports.tifa {
		src.WriteString("\"github.com/liustack/tifa\"\n")
	}
	src.WriteString("\"github.com/liustack/tifa/server\"\n\n")
	for _, path := range imports.order {
		fmt.Fprintf(&src, "%s %q\n", imports.byPath[path], path)
	}
	src.WriteString(")\n\n")
	src.WriteString(routes.String())
	routesGo, err := gofmt("routes.go", src.String())
	if err != nil {
		return nil, err
	}

	var main strings.Builder
	main.WriteString(header + "package main\n\nimport (\n\"embed\"\n\n")
	main.WriteString("\"github.com/liustack/tifa/server\"\n")
	if len(m.Hooks) > 0 {
		fmt.Fprintf(&main, "\nhooks %q\n", m.Module)
	}
	main.WriteString(")\n\n")
	if configName != "" {
		fmt.Fprintf(&main, "// config is the project %s, the settings layer below --config.\n//\n//go:embed %s\nvar config []byte\n\n", configName, configName)
	}
	main.WriteString("// dist holds what tifa build bundles: build.json, the SSR bundle, the browser assets and\n// the public files.\n//\n//go:embed all:dist\nvar dist embed.FS\n\n")
	main.WriteString("func main() {\nserver.Main(server.App{\n")
	if len(m.Hooks) > 0 {
		main.WriteString("Hooks: server.Hooks{\n")
		for _, h := range m.Hooks {
			fmt.Fprintf(&main, "%s: hooks.%s,\n", h, h)
		}
		main.WriteString("},\n")
	}
	main.WriteString("Layouts: layouts,\nRoutes: routes,\nDist: dist,\n")
	if configName != "" {
		fmt.Fprintf(&main, "ConfigName: %q,\nConfig: config,\n", configName)
	}
	main.WriteString("})\n}\n")
	mainGo, err := gofmt("main.go", main.String())
	if err != nil {
		return nil, err
	}
	return map[string][]byte{"main.go": mainGo, "routes.go": routesGo}, nil
}

// goImports names the imported packages of routes.go after their directory IDs, such as
// app_projects_list for app/projects/list, so names never clash with tifa or server.
type goImports struct {
	byPath map[string]string
	order  []string // import paths in first-use order, which follows the manifest order
	tifa   bool
}

func (g *goImports) alias(path, id string) string {
	if name, ok := g.byPath[path]; ok {
		return name
	}
	name := strings.Map(func(r rune) rune {
		if r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r) {
			return r
		}
		return '_'
	}, id)
	base := name
	for i := 2; slices.ContainsFunc(g.order, func(p string) bool { return g.byPath[p] == name }); i++ {
		name = base + "_" + strconv.Itoa(i)
	}
	g.byPath[path] = name
	g.order = append(g.order, path)
	return name
}

// load wraps a Load in tifa.Use, so the run the server starts and the runs other Loads ask for
// through tifa.Use are the same one.
func (g *goImports) load(path, id string) string {
	g.tifa = true
	return fmt.Sprintf("func(c *tifa.Ctx) (any, error) { return tifa.Use(c, %s.Load) }", g.alias(path, id))
}

func stringSlice(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

func gofmt(name, src string) ([]byte, error) {
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("codegen: %s does not parse: %w\n%s", name, err, src)
	}
	return out, nil
}
