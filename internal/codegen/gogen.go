const header = "// Code generated by tifa. DO NOT EDIT.\n\n"

// AppPackage is the directory under Dir of the package that holds the application as tifa build
// found it, the variable App. The generated main serves it, and the tests of the app start it
// with tifatest.Start, importing it as <module>/.tifa/tifaapp.
const AppPackage = "tifaapp"

// generateGo writes tifaapp/app.go, which describes the application with direct references to its
// hooks and its Load, Layout and method handler functions, and main.go, which hands it to
// server.Main, or to server.DevMain for tifa dev.
func generateGo(m *analyze.Manifest, settings map[string]string, dev bool) (map[string][]byte, error) {
	fingerprint, err := Fingerprint(m, settings)
	if err != nil {
		return nil, err
	}
	appGo, err := appSource(m, settings, fingerprint)
	if err != nil {
		return nil, err
	}

	var main strings.Builder
	// time/tzdata lets time.LoadLocation in the app's Go code find every time zone where the
	// system has no zoneinfo, as in a scratch container. Intl and Temporal in the VMs use quickjs's
	// own zone data.
	main.WriteString(header + "package main\n\nimport (\n\"embed\"\n_ \"time/tzdata\"\n\n")
	main.WriteString("\"github.com/liustack/tifa/server\"\n\n")
	fmt.Fprintf(&main, "%q\n)\n\n", m.Module+"/"+Dir+"/"+AppPackage)
	main.WriteString("// dist holds what tifa build bundles: build.json, the SSR bundle, the browser assets and\n// the public files.\n//\n//go:embed all:dist\nvar dist embed.FS\n\n")
	entry := "Main"
	if dev {
		entry = "DevMain"
	}
	fmt.Fprintf(&main, "func main() {\napp := tifaapp.App\napp.Dist = dist\nserver.%s(app)\n}\n", entry)
	mainGo, err := gofmt("main.go", main.String())
	if err != nil {
		return nil, err
	}
	return map[string][]byte{"main.go": mainGo, AppPackage + "/app.go": appGo}, nil
}

// Fingerprint is the hash of the application table that tifaapp/app.go holds for m and the runtime
// settings of the project tifa.yaml: the generated file says it as App.Fingerprint, and tifatest
// compares it with the one of a fresh analysis to tell a table older than the routes.
func Fingerprint(m *analyze.Manifest, settings map[string]string) (string, error) {
	src, err := appSource(m, settings, "")
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(src)
	return hex.EncodeToString(sum[:16]), nil
}

// AppFingerprint is Fingerprint with the runtime settings of the tifa.yaml in root.
func AppFingerprint(root string, m *analyze.Manifest) (string, error) {
	_, settings, err := project(root)
	if err != nil {
		return "", err
	}
	return Fingerprint(m, settings)
}

// appSource writes tifaapp/app.go with fingerprint as App.Fingerprint, which is left out when it
// is empty.
func appSource(m *analyze.Manifest, settings map[string]string, fingerprint string) ([]byte, error) {
	if m.Session != nil && m.Session.Name == "" {
		return nil, fmt.Errorf("the session type %s cannot be written in the generated main, which registers it when the program starts: make it an exported named struct type, not a generic one", m.Session.Type)
	}
	imports := goImports{byPath: map[string]string{}}

	var app strings.Builder
	app.WriteString("// App is the application as tifa build found it: the hooks of hooks.go, the Layouts and\n// routes, the session type and the runtime settings of tifa.yaml. The main of .tifa serves it,\n// and the tests of the app start it with tifatest.Start.\n")
	app.WriteString("var App = server.App{\n")
	if len(m.Hooks) > 0 {
		app.WriteString("Hooks: server.Hooks{\n")
		for _, h := range m.Hooks {
			fmt.Fprintf(&app, "%s: hooks.%s,\n", h, h)
		}
		app.WriteString("},\n")
	}
	app.WriteString("Layouts: []server.Layout{\n")
	for _, l := range m.Layouts {
		fmt.Fprintf(&app, "{\nID: %q,\nPath: %q,\n", l.ID, l.Path)
		if l.Load != nil {
			fmt.Fprintf(&app, "Load: %s,\n", imports.load(l.Package, l.Dir, "Layout"))
			if l.Load.HTML {
				app.WriteString("HTML: true,\n")
			}
		}
		fmt.Fprintf(&app, "SSR: %t,\n", l.SSR)
		if len(l.Languages) > 0 {
			fmt.Fprintf(&app, "Languages: %s,\n", stringSlice(l.Languages))
		}
		app.WriteString("},\n")
	}
	app.WriteString("},\nRoutes: []server.Route{\n")
	for _, r := range m.Routes {
		fmt.Fprintf(&app, "{\nID: %q,\nPath: %q,\nPage: %t,\n", r.ID, r.Path, r.Page)
		if r.Load != nil {
			fmt.Fprintf(&app, "Load: %s,\n", imports.load(r.Package, r.Dir, "Load"))
		}
		for _, h := range r.Handlers {
			fmt.Fprintf(&app, "%s: %s,\n", h.Method, imports.handler(r.Package, r.Dir, h))
		}
		// A variable set from a setting is read when the program starts.
		if r.BodyLimit {
			fmt.Fprintf(&app, "BodyLimit: int64(%s.BodyLimit),\n", imports.alias(r.Package, r.Dir))
		}
		if r.ReadTimeout {
			fmt.Fprintf(&app, "ReadTimeout: %s.ReadTimeout,\n", imports.alias(r.Package, r.Dir))
		}
		fmt.Fprintf(&app, "SSR: %t,\n", r.SSR)
		if !r.RenderCache {
			app.WriteString("NoRenderCache: true,\n")
		}
		if r.Cache > 0 {
			fmt.Fprintf(&app, "Cache: %d, // %s\n", int64(r.Cache), r.Cache)
			if names := cacheQuery(m, r); len(names) > 0 {
				fmt.Fprintf(&app, "Query: %s,\n", stringSlice(names))
			}
		}
		fmt.Fprintf(&app, "Layouts: %s,\n", stringSlice(r.Layouts))
		if r.Load != nil && r.Load.HTML {
			app.WriteString("HTML: true,\n")
		}
		if len(r.Languages) > 0 {
			fmt.Fprintf(&app, "Languages: %s,\n", stringSlice(r.Languages))
		}
		app.WriteString("},\n")
	}
	app.WriteString("},\n")
	// The session type is registered when the process starts, so that a request which holds a
	// session from before a restart gets its Exposed data too.
	if m.Session != nil {
		fmt.Fprintf(&app, "Session: server.SessionOf[sessiontype.%s],\n", m.Session.Name)
	}
	if m.I18n != nil {
		fmt.Fprintf(&app, "I18n: &server.I18n{\nDefault: %q,\n", m.I18n.Default)
		if m.I18n.Always {
			app.WriteString("Always: true,\n")
		}
		fmt.Fprintf(&app, "Languages: %s,\n", stringSlice(m.I18n.Languages))
		if m.I18n.SiteURL != "" {
			fmt.Fprintf(&app, "SiteURL: %q,\n", m.I18n.SiteURL)
		}
		app.WriteString("},\n")
	}
	if len(settings) > 0 {
		// The runtime settings of tifa.yaml, which tifa build checked: the program does not read the file.
		app.WriteString("Settings: map[string]string{\n")
		for _, key := range slices.Sorted(maps.Keys(settings)) {
			fmt.Fprintf(&app, "%q: %q,\n", key, settings[key])
		}
		app.WriteString("},\n")
	}
	if fingerprint != "" {
		fmt.Fprintf(&app, "Fingerprint: %q,\n", fingerprint)
	}
	app.WriteString("}\n")

	var src strings.Builder
	src.WriteString(header + "// Package tifaapp is the application as tifa build found it. Import it in a test of the app\n// to start the app with tifatest.Start.\npackage tifaapp\n\nimport (\n")
	if imports.tifa {
		src.WriteString("\"github.com/liustack/tifa\"\n")
	}
	src.WriteString("\"github.com/liustack/tifa/server\"\n")
	if len(m.Hooks) > 0 {
		fmt.Fprintf(&src, "\nhooks %q\n", m.Module)
	} else if len(m.Settings) > 0 || m.Content != nil {
		// config.go defines the settings of the app when the package starts, and content.go
		// declares its content collections.
		fmt.Fprintf(&src, "\n_ %q\n", m.Module)
	}
	if m.Session != nil {
		fmt.Fprintf(&src, "\nsessiontype %q\n", m.Session.Package)
	}
	if len(imports.order) > 0 {
		src.WriteString("\n")
	}
	for _, path := range imports.order {
		fmt.Fprintf(&src, "%s %q\n", imports.byPath[path], path)
	}
	src.WriteString(")\n\n")
	src.WriteString(app.String())
	return gofmt(AppPackage+"/app.go", src.String())
}

// goImports names the imported packages of tifaapp/app.go after their directory IDs, such as
// app_projects_list for app/projects/list, so names never clash with tifa, server, hooks or
// sessiontype: a directory ID starts with app.
type goImports struct {
	byPath map[string]string
	order  []string // import paths in first-use order, which follows the manifest order
	tifa   bool
}

// handler refers to the method handler h of the package at path. A handler that takes an input
// or returns a result goes through the adapter of the server package for its signature, with the
// input read from the query string for GET and DELETE and from the request body otherwise, a form
// for an input that holds files.
func (g *goImports) handler(path, dir string, h analyze.Handler) string {
	fn := g.alias(path, dir) + "." + h.Method
	bind := "(*tifa.Ctx).Bind"
	switch {
	case h.Method == "GET" || h.Method == "DELETE":
		bind = "(*tifa.Ctx).BindQuery"
	case h.Form:
		bind = "server.BindForm"
	}
	switch {
	case h.Input != "" && h.Output != "":
		g.tifa = true
		return fmt.Sprintf("server.InputOutput(%s, %s)", fn, bind)
	case h.Input != "":
		g.tifa = true
		return fmt.Sprintf("server.Input(%s, %s)", fn, bind)
	case h.Output != "":
		return fmt.Sprintf("server.Output(%s)", fn)
	}
	return fn
}

// alias names the import of a package after its directory, made a Go identifier.
func (g *goImports) alias(path, dir string) string {
	if name, ok := g.byPath[path]; ok {
		return name
	}
	name := strings.Map(func(r rune) rune {
		if r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r) {
			return r
		}
		return '_'
	}, dir)
	base := name
	for i := 2; slices.ContainsFunc(g.order, func(p string) bool { return g.byPath[p] == name }); i++ {
		name = base + "_" + strconv.Itoa(i)
	}
	g.byPath[path] = name
	g.order = append(g.order, path)
	return name
}

// load wraps the Load of a route or the Layout function of a Layout in tifa.Use, so the run the
// server starts and the runs other Loads ask for through tifa.Use are the same one.
func (g *goImports) load(path, dir, fn string) string {
	g.tifa = true
	return fmt.Sprintf("func(c *tifa.Ctx) (any, error) { return tifa.Use(c, %s.%s) }", g.alias(path, dir), fn)
}

func stringSlice(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

func gofmt(name, src string) ([]byte, error) {
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("codegen: %s does not parse: %w\n%s", name, err, src)
	}
	return out, nil
}

// cacheQuery lists the query parameters read by the Load of the route and by the Layout functions
// around it, sorted: the whole-page cache of the route keeps them whatever cache.ignore_query says.
func cacheQuery(m *analyze.Manifest, r analyze.Route) []string {
	var names []string
	if r.Load != nil {
		names = append(names, r.Load.AllQuery...)
	}
	for _, id := range r.Layouts {
		for _, l := range m.Layouts {
			if l.ID == id && l.Load != nil {
				names = append(names, l.Load.AllQuery...)
			}
		}
	}
	slices.Sort(names)
	return slices.Compact(names)
}
