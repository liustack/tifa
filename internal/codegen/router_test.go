// routerBuild bundles the tests with Vite for Node to run. router.test.tsx runs the server
// renders and the browser routers on Node's build of TanStack, head.test.tsx the head code of the
// browser on its browser build, call.test.ts the generated handler functions, session.test.tsx the copy of the session. router.test.tsx and
// head.test.tsx are bundled once more with the lazyRoutes plugin, which the browser build of an
// application has, into *.lazy.mjs: their route modules load when a route needs them, also those
// that export head. seroval gets the changes of the SSR bundle, so the server renders write the
// data of a page as the bundle does, and React DOM gets the prerenderToString the runtime renders
// with.
const tifaHeader = "// Code generated by tifa. DO NOT EDIT.\n\n"

const routerBuild = `import { build } from 'vite'
import { generated, lazyRoutes, prerenderPlugin, serovalPlugin } from './.tifa/vite/plugin.js'
const assets = '<link rel="stylesheet" href="/assets/app.css"><script type="module" src="/assets/app.js"></script>'
const entries = [['router.test.tsx', 'node', false], ['head.test.tsx', 'browser', false], ['call.test.ts', 'node', false],
  ['session.test.tsx', 'node', false], ['router.test.tsx', 'node', true], ['head.test.tsx', 'browser', true]]
for (const [entry, platform, lazy] of entries) {
  await build({
    configFile: false,
    logLevel: 'warn',
    plugins: lazy ? [generated(), lazyRoutes(['ssr']), serovalPlugin(), prerenderPlugin()] : [generated(), serovalPlugin(), prerenderPlugin()],
    resolve: { tsconfigPaths: true },
    define: { 'process.env.NODE_ENV': '"production"', 'import.meta.env.DEV': 'true', __TIFA_ASSETS__: JSON.stringify(assets), __LAZY_ROUTES__: String(lazy) },
    environments: { ssr: { resolve: { noExternal: true, conditions: [platform, 'import', 'module', 'default'] } } },
    build: {
      ssr: entry,
      outDir: lazy ? 'out/lazy' : 'out',
      emptyOutDir: false,
      minify: false,
      rolldownOptions: { output: { format: 'es', entryFileNames: entry.replace(/\.tsx?$/, '.mjs') } },
    },
  })
}
`

// TestGeneratedRouterBehaves runs testdata/router/router.test.tsx in Node against the route
// tree generated for testdata/router: server renders through the SSR entry, client navigation
// on a memory history, and the data collector against a stubbed fetch. It needs node and the
// packages of test/apps/pages, Vite among them:
//
//	(cd test/apps/pages && pnpm install --frozen-lockfile)
func TestGeneratedRouterBehaves(t *testing.T) {
	node, root, modules, run := routerApp(t, filepath.Join("testdata", "router"), routerBuild, nil)
	run("build.mjs")
	for _, name := range []string{"router.test", "head.test", "call.test", "session.test", "lazy/router.test", "lazy/head.test"} {
		run(filepath.Join("out", filepath.FromSlash(name)+".mjs"))
	}

	// The generated tree, the runtime and the fixture's TSX type-check together.
	tsc := exec.Command(node, filepath.Join(modules, "typescript", "bin", "tsc"), "--noEmit", "-p", ".")
	tsc.Dir = root
	if output, err := tsc.CombinedOutput(); err != nil {
		t.Fatalf("tsc: %v\n%s", err, output)
	}

	// An app that never calls tifa.SetSession cannot call useSession: the type refuses it.
	disabled := tifaHeader + "export type SessionEnabled = false\nexport type SessionData = never\n"
	if err := os.WriteFile(filepath.Join(root, ".tifa", "session.gen.ts"), []byte(disabled), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "disabled.ts"), []byte("import { useSession } from 'tifa/client'\nuseSession()\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	// A tifa.HTML value is no string.
	raw := "import type { PageData } from './.tifa/app/article/route.gen'\n" +
		"export const text: string = ({} as PageData).body\n" +
		"export const length: number = ({} as PageData).body.length\n"
	if err := os.WriteFile(filepath.Join(root, "raw.ts"), []byte(raw), 0o644); err != nil {
		t.Fatal(err)
	}
	tsc = exec.Command(node, filepath.Join(modules, "typescript", "bin", "tsc"), "--noEmit", "-p", ".")
	tsc.Dir = root
	output, err := tsc.CombinedOutput()
	if err == nil || !strings.Contains(string(output), "disabled.ts(2,1): error TS2554") {
		t.Fatalf("useSession in an app without sessions: err %v, output\n%s", err, output)
	}
	for _, want := range []string{"raw.ts(2,", "raw.ts(3,"} {
		if !strings.Contains(string(output), want) {
			t.Errorf("a tifa.HTML value used as a string type-checks (no error at %s):\n%s", want, output)
		}
	}
}

// publicBuild is routerBuild for the one test of testdata/routerpublic.
var publicBuild = strings.Replace(routerBuild, "const entries = [['router.test.tsx', 'node', false], ['head.test.tsx', 'browser', false], ['call.test.ts', 'node', false],\n  ['session.test.tsx', 'node', false], ['router.test.tsx', 'node', true], ['head.test.tsx', 'browser', true]]", "const entries = [['public.test.tsx', 'node', false]]", 1)

// TestGeneratedRouterLeavesPublicFiles runs testdata/routerpublic/public.test.tsx against an app
// with a parameter folder at the root of app/, where /favicon.svg also matches the route /{lang}.
func TestGeneratedRouterLeavesPublicFiles(t *testing.T) {
	node, root, modules, run := routerApp(t, filepath.Join("testdata", "routerpublic"), publicBuild, map[string]string{"public/a?b.txt": "x"})
	run("build.mjs")
	run(filepath.Join("out", "public.test.mjs"))
	tsc := exec.Command(node, filepath.Join(modules, "typescript", "bin", "tsc"), "--noEmit", "-p", ".")
	tsc.Dir = root
	if output, err := tsc.CombinedOutput(); err != nil {
		t.Fatalf("tsc: %v\n%s", err, output)
	}
}

// routerApp generates the app in src, with the files of extra added, in a temporary directory, links the packages of
// test/apps/pages there and writes build as build.mjs. It returns node, the directory, the
// packages and a function that runs a script in the directory.
func routerApp(t *testing.T, src, build string, extra map[string]string) (node, root, modules string, run func(args ...string)) {
	t.Helper()
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node is not installed")
	}
	pages, err := filepath.Abs(filepath.Join("..", "..", "test", "apps", "pages"))
	if err != nil {
		t.Fatal(err)
	}
	modules = filepath.Join(pages, "node_modules")
	if _, err := os.Stat(filepath.Join(modules, "vite")); err != nil {
		t.Skip("run pnpm install --frozen-lockfile in test/apps/pages first")
	}

	// The app is generated from a copy, so that files whose names a Go module cannot hold (see
	// module.CheckFilePath) are made here and not checked in.
	root = t.TempDir()
	if err := os.CopyFS(root, os.DirFS(src)); err != nil {
		t.Fatal(err)
	}
	repo, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	gomod := filepath.Join(root, "go.mod")
	data, err := os.ReadFile(gomod)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(gomod, []byte(strings.Replace(string(data), "=> ../../../..", "=> "+repo, 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	for name, text := range extra {
		if err := os.WriteFile(filepath.Join(root, filepath.FromSlash(name)), []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	m, err := analyze.Analyze(root)
	if err != nil {
		t.Fatal(err)
	}
	front := bundle.NewNode(pages, io.Discard)
	defer front.Close()
	files, err := Generate(root, m, false, front.Exports)
	if err != nil {
		t.Fatal(err)
	}
	if err := Write(root, files); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(modules, filepath.Join(root, "node_modules")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "build.mjs"), []byte(build), 0o644); err != nil {
		t.Fatal(err)
	}
	// The tsconfig.json of an application, which declares tifa/client for Vite and TypeScript.
	tsconfig := `{ "extends": "./.tifa/tsconfig.json", "compilerOptions": { "paths": { "@/*": ["./*"], "tifa/client": ["./.tifa/runtime/client.ts"] } }, "include": ["**/*", ".tifa/**/*"] }`
	if err := os.WriteFile(filepath.Join(root, "tsconfig.json"), []byte(tsconfig), 0o644); err != nil {
		t.Fatal(err)
	}
	run = func(args ...string) {
		t.Helper()
		cmd := exec.Command(node, args...)
		cmd.Dir = root
		output, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("node %v: %v\n%s", args, err, output)
		}
		t.Logf("%v:\n%s", args, output)
	}
	return node, root, modules, run
}
