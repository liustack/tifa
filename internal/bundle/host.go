package bundle

import (
	"errors"
)

// hostHeader starts js/runtime/host.js.
const hostHeader = "// Code generated by go generate ./js from js/host. DO NOT EDIT.\n"

// Host bundles the SSR host patches of dir (host.ts with its pinned node_modules) into one
// script with no imports left, built like an SSR bundle so core-js gets the QuickJS adapter.
// The tifa repository checks the result in as js/runtime/host.js, so applications do not
// install the patch packages.
func Host(dir string) ([]byte, error) {
	result, err := buildSSR(SSROptions{Root: dir, Entry: "host.ts"}, false)
	if err != nil {
		return nil, err
	}
	if len(result.OutputFiles) != 1 {
		return nil, errors.New("host bundle has no single output")
	}
	return append([]byte(hostHeader), result.OutputFiles[0].Contents...), nil
}
