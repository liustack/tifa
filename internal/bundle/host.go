package bundle

import (
	"io"
	"os"
	"path/filepath"

	"github.com/liustack/tifa/js"
)

// hostHeader starts js/runtime/host.js.
const hostHeader = "// Code generated by go generate ./js from js/host. DO NOT EDIT.\n"

// Host bundles the SSR host patches of dir (host.ts with its pinned node_modules, Vite among
// them) into one script with no imports left, built like an SSR bundle so core-js gets the QuickJS
// adapter. The tifa repository checks the result in as js/runtime/host.js, so applications do not
// install the patch packages.
func Host(dir string) ([]byte, error) {
	code, _, err := script(dir, dir, "host.ts", os.Stderr)
	if err != nil {
		return nil, err
	}
	return append([]byte(hostHeader), code...), nil
}

// script builds file, relative to dir, alone like an SSR bundle: with the SSR rules of the tifa
// plugin, without a Vite config, minified. It returns the code and the modules in it. Vite loads
// from the node_modules of vite, a directory, and output gets what Node and Vite print.
func script(vite, dir, file string, output io.Writer) (string, []string, error) {
	dir, err := filepath.Abs(dir)
	if err != nil {
		return "", nil, err
	}
	plugin, err := os.CreateTemp("", "tifa-vite-plugin-*.mjs")
	if err != nil {
		return "", nil, err
	}
	defer os.Remove(plugin.Name())
	if _, err := plugin.WriteString(js.VitePlugin); err != nil {
		plugin.Close()
		return "", nil, err
	}
	if err := plugin.Close(); err != nil {
		return "", nil, err
	}
	n := NewNode(vite, output)
	defer n.Close()
	var result struct {
		Code    string
		Modules []string
	}
	if err := n.call("script", map[string]any{"dir": dir, "file": file, "plugin": plugin.Name()}, &result); err != nil {
		return "", nil, err
	}
	return result.Code, result.Modules, nil
}
