// Writes posts.gen.ts, the Markdown of the journal posts of examples/shop, so that the port does
// not read files at run time (a bundler cannot find them). Run it after a post changes:
//   node test/compare/domain/store/journal/genPosts.ts
// The data parity test fails when posts.gen.ts is out of date.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = join(here, '..', '..', '..', '..', '..', 'examples', 'shop', 'app', 'store', 'journal', 'posts')
const bodies: Record<string, string> = {}
for (const name of readdirSync(source).sort()) {
  if (name.endsWith('.md')) bodies[name.slice(0, -'.md'.length)] = readFileSync(join(source, name), 'utf8')
}
const text = '// Generated by genPosts.ts from the posts of examples/shop. Do not edit.\n' +
  'export const bodies: Record<string, string> = ' + JSON.stringify(bodies, null, 2) + '\n'
writeFileSync(join(here, 'posts.gen.ts'), text)
