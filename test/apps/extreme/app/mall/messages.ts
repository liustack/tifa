const resources = { 'zh-CN': { translation: zhCN }, 'en-US': { translation: enUS } }

const instances = new Map<string, i18n>()

// marketI18n returns the i18next instance of a language, made once.
export function marketI18n(lang: string): i18n {
  let instance = instances.get(lang)
  if (!instance) {
    instance = i18next.createInstance()
    instance.init({ lng: lang, fallbackLng: false, resources, initAsync: false, interpolation: { escapeValue: false } })
    instances.set(lang, instance)
  }
  return instance
}
