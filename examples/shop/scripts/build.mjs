import { build } from 'esbuild'
import ts from 'typescript'
import { execFileSync } from 'node:child_process'
import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { buildSSR } from './ssr-build.mjs'

const root = process.cwd()
const app = path.join(root, 'web/app')
const out = path.join(root, 'internal/ssr/assets')
await mkdir('web/generated', { recursive: true })
const contracts = JSON.parse(
  execFileSync('go', ['run', './cmd/contracts'], { encoding: 'utf8' }),
)
await writeFile('web/generated/contracts.ts', contracts.typescript)

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const lists = await Promise.all(
    entries.map((e) =>
      e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)],
    ),
  )
  return lists.flat().sort()
}

// Parse a deliberately small declaration language. Never execute the data module.
function literal(node) {
  if (ts.isStringLiteral(node)) return node.text
  if (ts.isObjectLiteralExpression(node)) {
    const object = {}
    for (const p of node.properties) {
      if (
        !ts.isPropertyAssignment(p) ||
        !(ts.isIdentifier(p.name) || ts.isStringLiteral(p.name))
      )
        throw new Error('Data declarations require literal properties')
      const key = p.name.text
      if (
        Object.hasOwn(object, key) ||
        ['__proto__', 'constructor', 'prototype'].includes(key)
      )
        throw new Error(`Invalid declaration key: ${key}`)
      object[key] = literal(p.initializer)
    }
    return object
  }
  throw new Error('Data declarations only accept object and string literals')
}

async function declaration(file) {
  let source
  try {
    source = await readFile(file, 'utf8')
  } catch (e) {
    if (e.code === 'ENOENT') return {}
    throw e
  }
  const ast = ts.createSourceFile(
    file,
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  )
  const exports = ast.statements.filter(ts.isExportAssignment)
  if (
    exports.length !== 1 ||
    ast.statements.some(
      (n) => !ts.isImportDeclaration(n) && !ts.isExportAssignment(n),
    )
  )
    throw new Error(`Unsupported data declaration: ${file}`)
  const call = exports[0].expression
  if (
    !ts.isCallExpression(call) ||
    !ts.isIdentifier(call.expression) ||
    call.expression.text !== 'defineData' ||
    call.arguments.length !== 1
  )
    throw new Error(`Expected defineData in ${file}`)
  return literal(call.arguments[0])
}

const components = (await walk(app)).filter((f) =>
  /\/(page|layout)\.tsx$/.test(f),
)
const records = []
for (const file of components) {
  const kind = path.basename(file, '.tsx')
  const dir = path.relative(app, path.dirname(file)).split(path.sep).join('/')
  const id = `${kind}:${dir || 'root'}`
  const dataFile = file.replace('.tsx', '.data.ts')
  const data = await declaration(dataFile)
  const record = { id, kind, dir, pattern: '/' + dir, data, file }
  for (const descriptor of Object.values(data)) {
    if (
      !Object.keys(descriptor).every((k) => ['source', 'params'].includes(k)) ||
      typeof descriptor.source !== 'string'
    )
      throw new Error(`Invalid data source in ${dataFile}`)
    const required = contracts.sources[descriptor.source]
    if (
      !required ||
      required.toSorted().join() !==
        Object.keys(descriptor.params || {})
          .sort()
          .join()
    )
      throw new Error(
        `Unknown source or incorrect parameters in ${dataFile}: ${descriptor.source}`,
      )
    for (const binding of Object.values(descriptor.params || {})) {
      if (
        Object.keys(binding).join() !== 'routeParam' ||
        !dir.includes(`[${binding.routeParam}]`)
      )
        throw new Error(`Unknown route parameter in ${dataFile}`)
    }
  }
  records.push(record)
  const hook = kind === 'page' ? 'usePageData' : 'useLayoutData'
  const generated = Object.keys(data).length
    ? `import type declaration from './${kind}.data'\nimport { useData } from '@go-quick/data'\nexport const ${hook} = () => useData<typeof declaration>(${JSON.stringify(
        id,
      )})\n`
    : `export const ${hook} = () => ({})\n`
  await writeFile(
    file.replace('.tsx', '.generated.ts'),
    '// Generated by pnpm run build.\n' + generated,
  )
}

const rootLayout = records.find((r) => r.id === 'layout:root')
if (!rootLayout) throw new Error('web/app/layout.tsx is required')
const layouts = records
  .filter((r) => r.kind === 'layout')
  .sort((a, b) => a.dir.length - b.dir.length)
for (const r of records) {
  if (r === rootLayout) continue
  const ancestors = layouts.filter(
    (l) =>
      l !== r &&
      (l.dir === '' ||
        r.dir.startsWith(l.dir + '/') ||
        (r.kind === 'page' && r.dir === l.dir)),
  )
  r.parent = ancestors.at(-1).id
}
const manifest = records.map(({ file, ...r }) => r)
const imports = records
  .map(
    (r, i) =>
      `import C${i} from ${JSON.stringify(
        '../app/' + (r.dir ? r.dir + '/' : '') + r.kind,
      )}`,
  )
  .join('\n')
const variable = (r) => (r === rootLayout ? 'root' : `r${records.indexOf(r)}`)
const generated = [
  '// Generated by pnpm run build.',
  "import { createRoute, type AnyRootRoute } from '@tanstack/react-router'",
  imports,
  `export const RootLayout = C${records.indexOf(rootLayout)}`,
  'export function createRouteTree(root: AnyRootRoute) {',
]
const ordered = [
  ...layouts.filter((r) => r !== rootLayout),
  ...records.filter((r) => r.kind === 'page'),
]
for (const r of ordered) {
  const parent = records.find((p) => p.id === r.parent)
  const relative =
    r.dir
      .slice(parent.dir.length)
      .replace(/^\//, '')
      .replace(/\[([^\]]+)\]/g, '$$$1') || '/'
  const scopedParams = [...r.dir.matchAll(/\[([^\]]+)\]/g)]
    .map((m) => `params[${JSON.stringify(m[1])}]`)
    .join(',')
  generated.push(
    `const ${variable(r)} = createRoute({ getParentRoute: () => ${variable(
      parent,
    )}, path: ${JSON.stringify(relative)}, component: C${records.indexOf(
      r,
    )}, remountDeps: ({params}) => [${scopedParams}] })`,
  )
}
function subtree(r) {
  const children = records.filter((c) => c.parent === r.id)
  return (
    variable(r) +
    (children.length
      ? `.addChildren([${children.map(subtree).join(',')}])`
      : '')
  )
}
generated.push(`return ${subtree(rootLayout)}`, '}')
await writeFile('web/generated/routes.ts', generated.join('\n'))

await rm(out, { recursive: true, force: true })
await mkdir(path.join(out, 'public'), { recursive: true })
await writeFile(
  path.join(out, 'routes.json'),
  JSON.stringify(manifest, null, 2),
)

const shared = {
  bundle: true,
  target: 'es2022',
  tsconfig: 'tsconfig.json',
  metafile: true,
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
}
await buildSSR({ root })

const client = await build({
  ...shared,
  entryPoints: ['web/client.tsx'],
  outdir: path.join(out, 'public'),
  platform: 'browser',
  format: 'esm',
  splitting: true,
  minify: true,
  entryNames: 'app-[hash]',
  chunkNames: 'chunk-[hash]',
})
const [entry, info] = Object.entries(client.metafile.outputs).find(
  ([, v]) => v.entryPoint === 'web/client.tsx',
)
const files = await walk(out)
const hash = createHash('sha256')
for (const f of files) hash.update(await readFile(f))
const assets = {
  buildId: hash.digest('hex').slice(0, 16),
  script: '/assets/' + path.basename(entry),
  style: '/assets/' + path.basename(info.cssBundle),
}
await writeFile(path.join(out, 'build.json'), JSON.stringify(assets))
console.log(
  `Built ${records.filter((r) => r.kind === 'page').length} pages and ${
    layouts.length
  } layouts · ${assets.buildId}`,
)
